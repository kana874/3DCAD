"""Allowlisted modeling commands for the Fusion-style FreeCAD Web palette.

Sent through the existing guarded Qt/Python bridge, never exposed as arbitrary
Python. Actions call native FreeCADGui.runCommand (interactive task dialogs and
undo behavior remain FreeCAD's). No geometry is generated by the overlay.
"""
import json
import sys

_REQUEST = "__FUSION_DESIGN_REQUEST__"
_REQUEST_ID = __FUSION_DESIGN_ID__
_OUTPUT = "/tmp/fusion-design-response.json"

# Prefer Part Design's sketch creation because it auto-creates a Body if needed.
COMMANDS = {
    "new": ("Std_New",),
    "body": ("PartDesign_Body",),
    "sketch": ("PartDesign_NewSketch", "Sketcher_NewSketch"),
    "line": ("Sketcher_CreateLine",),
    "rectangle": ("Sketcher_CreateRectangle",),
    "circle": ("Sketcher_CreateCircle",),
    "arc": ("Sketcher_CreateArc",),
    "dimension": ("Sketcher_Dimension",),
    "trim": ("Sketcher_Trimming",),
    "construction": ("Sketcher_ToggleConstruction",),
    "leave_sketch": ("Sketcher_LeaveSketch",),
    "pad": ("PartDesign_Pad",),
    "pocket": ("PartDesign_Pocket",),
    "revolve": ("PartDesign_Revolution",),
    "hole": ("PartDesign_Hole",),
    "fillet": ("PartDesign_Fillet",),
    "chamfer": ("PartDesign_Chamfer",),
    "mirror": ("PartDesign_Mirrored",),
    "linear_pattern": ("PartDesign_LinearPattern",),
}
SKETCH_ONLY = frozenset(("line", "rectangle", "circle", "arc", "dimension",
                         "trim", "construction", "leave_sketch"))
SOLID_ONLY = frozenset(("pad", "pocket", "revolve", "hole", "fillet",
                        "chamfer", "mirror", "linear_pattern"))


def command_name(gui, action):
    names = COMMANDS[action]
    try:
        listed = set(gui.listCommands())
    except Exception:
        listed = set()
    for name in names:
        try:
            if name in listed or gui.Command.get(name) is not None:
                return name
        except Exception:
            pass
    return None


def current_state(app, gui):
    document = getattr(app, "ActiveDocument", None)
    in_edit = False
    try:
        gdoc = gui.activeDocument()
        if gdoc is not None:
            in_edit = bool(gdoc.getInEdit())
    except Exception:
        # An unavailable API is not evidence the sketch editor is active.
        pass
    try:
        selected = len(gui.Selection.getSelectionEx()) if document else 0
    except Exception:
        selected = 0
    try:
        body_objects = document.findObjects("PartDesign::Body") if document else []
        has_body = bool(body_objects)
    except Exception:
        # Older builds may not support findObjects for Body. Inspect objects
        # without modifying the project and report whether one already exists.
        has_body = bool(document and any(
            getattr(obj, "TypeId", "") == "PartDesign::Body"
            for obj in getattr(document, "Objects", [])))
    available = {action: bool(command_name(gui, action))
                 for action in COMMANDS}
    # Gui.activeDocument().resetEdit() is the supported fallback when the
    # dedicated Sketcher_LeaveSketch command is not registered in this build.
    available["leave_sketch"] = bool(in_edit)
    return {
        "document": bool(document),
        "hasBody": has_body,
        "sketchEdit": in_edit,
        "selectionCount": selected,
        "available": available,
    }


def execute(app, gui, action):
    if action == "state":
        return {"ok": True, "message": "操作状態を取得しました。"}
    if action not in COMMANDS:
        return {"ok": False, "message": "未対応の操作です。"}
    state = current_state(app, gui)
    if action != "new" and not state["document"]:
        return {"ok": False, "message": "先に「新規設計」でドキュメントを作成してください。"}
    if action in SKETCH_ONLY and not state["sketchEdit"]:
        return {"ok": False, "message": "先にスケッチを作成して編集を開始してください。"}
    if action in SOLID_ONLY and state["sketchEdit"]:
        return {"ok": False, "message": "先に「スケッチ終了」を選んでください。"}
    if action in SOLID_ONLY and state["selectionCount"] == 0:
        return {"ok": False, "message": "モデルツリーでスケッチ、面、またはフィーチャを選択してください。"}
    if action == "sketch" and state["sketchEdit"]:
        return {"ok": False, "message": "スケッチ編集中です。いったん終了してください。"}
    if action == "leave_sketch":
        # FreeCAD's task panel may expose Sketcher_LeaveSketch; native
        # resetEdit is the documented fallback for edited sketch objects.
        command = command_name(gui, action)
        if command:
            gui.runCommand(command)
        else:
            gui.activeDocument().resetEdit()
        return {"ok": True, "command": command or "Gui.activeDocument().resetEdit",
                "message": "スケッチ編集を終了しました。"}
    command = command_name(gui, action)
    if not command:
        return {"ok": False, "message": "このWeb版ではコマンドを利用できません。"}
    # This may open a native Qt task panel or a plane-selection dialog.
    gui.runCommand(command)
    return {"ok": True, "command": command,
            "message": "FreeCADの操作パネルで次の操作を進めてください。"}


def main():
    import FreeCAD as app
    import FreeCADGui as gui
    # Command registration is lazy on some builds. Do not switch workbenches
    # while editing a sketch; doing so would disturb the active task.
    try:
        for module in ("PartDesignGui", "SketcherGui"):
            try:
                __import__(module)
            except Exception:
                pass
    except Exception:
        pass
    result = execute(app, gui, _REQUEST)
    result.update({"requestId": _REQUEST_ID, "state": current_state(app, gui)})
    return result


try:
    _result = main()
except Exception as error:
    _result = {"requestId": _REQUEST_ID, "ok": False,
               "message": "FreeCAD操作で例外が発生しました。",
               "error": repr(error)}
    sys.stderr.write("[fusion-design] " + repr(error) + "\n")
try:
    with open(_OUTPUT, "w", encoding="utf-8") as file:
        json.dump(_result, file, ensure_ascii=False)
except Exception as error:
    sys.stderr.write("[fusion-design] result write: " + repr(error) + "\n")
